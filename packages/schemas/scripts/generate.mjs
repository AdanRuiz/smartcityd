// Generates src/generated/ from the *.schema.json files:
//   validators.ts  precompiled Ajv validators (no eval: Cloudflare Workers and strict CSP forbid it)
//   types.ts       content types
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import Ajv2020Module from 'ajv/dist/2020.js'
import standaloneModule from 'ajv/dist/standalone/index.js'
import { compile } from 'json-schema-to-typescript'

const Ajv2020 = Ajv2020Module.default ?? Ajv2020Module
const standaloneCode = standaloneModule.default ?? standaloneModule

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outDir = join(root, 'src', 'generated')
const SUFFIX = '.schema.json'

const names = (await readdir(root)).filter((f) => f.endsWith(SUFFIX)).map((f) => f.slice(0, -SUFFIX.length)).sort()
const schemas = Object.fromEntries(
  await Promise.all(names.map(async (n) => [n, JSON.parse(await readFile(join(root, n + SUFFIX), 'utf8'))])),
)

await mkdir(outDir, { recursive: true })

// --- validators
// strictRequired is off for report_update's `anyOf: [{required: [status]}, {required: [body]}]`.
const ajv = new Ajv2020({
  strict: true,
  strictRequired: false,
  allowUnionTypes: true,
  code: { source: true, esm: true },
})
for (const n of names) ajv.addSchema(schemas[n], n)

const UCS2_REQUIRE = /require\("ajv\/dist\/runtime\/ucs2length"\)\.default/g
let code = standaloneCode(ajv, Object.fromEntries(names.map((n) => [n, n]))).replace(UCS2_REQUIRE, 'ucs2length')
if (/\brequire\(/.test(code)) throw new Error('generated validators still contain require(): inline that runtime helper')
code = `// @ts-nocheck\n// Generated by scripts/generate.mjs. Do not edit.\nimport { ucs2length } from '../ucs2length.js'\n${code}\n`
await writeFile(join(outDir, 'validators.ts'), code)

// --- types
// json-schema-to-typescript predates 2020-12: give it tuples in the old `items: [...]` form, and drop
// `anyOf` branches that only say `required` (a runtime rule that would turn the type into noise).
function forTypes(node) {
  if (Array.isArray(node)) return node.map(forTypes)
  if (node === null || typeof node !== 'object') return node
  const out = {}
  for (const [k, v] of Object.entries(node)) {
    if (k === 'prefixItems') {
      out.items = forTypes(v)
      out.additionalItems = false
    } else if (k === 'anyOf' && v.every((b) => Object.keys(b).join() === 'required')) continue
    else if (k !== '$defs' && k !== '$schema') out[k] = forTypes(v)
  }
  return out
}

// Every schema file is self-contained, so shared $defs (latlon, hex64…) are repeated. Merge them into
// one document so each becomes a single type, and fail if two files disagree on a definition.
const defs = {}
for (const n of names) {
  for (const [name, def] of Object.entries(schemas[n].$defs ?? {})) {
    const json = JSON.stringify(def)
    if (defs[name] && JSON.stringify(defs[name].source) !== json) {
      throw new Error(`$defs/${name} in ${n}${SUFFIX} differs from the same definition in another schema`)
    }
    defs[name] = { source: def, forTypes: forTypes(def) }
  }
}
const combined = {
  title: 'ContentBySchema',
  description: 'Content type of each schema file, by file name.',
  type: 'object',
  required: names,
  properties: Object.fromEntries(names.map((n) => [n, { $ref: `#/$defs/${schemas[n].title}` }])),
  $defs: {
    ...Object.fromEntries(Object.entries(defs).map(([name, d]) => [name, d.forTypes])),
    ...Object.fromEntries(names.map((n) => [schemas[n].title, forTypes(schemas[n])])),
  },
}
const types = await compile(combined, combined.title, {
  bannerComment: '// Generated by scripts/generate.mjs. Do not edit.',
  additionalProperties: false,
  ignoreMinAndMaxItems: true,
  style: { semi: false, singleQuote: true, printWidth: 120 },
})
await writeFile(join(outDir, 'types.ts'), types)

console.log(`generated validators and types for: ${names.join(', ')}`)
