// Extrae el mapa base de una ciudad del build diario de Protomaps (OpenStreetMap) y regenera src/files.ts.
// Uso: node scripts/extract.mjs <city id> <minLat,minLon,maxLat,maxLon> [--build 20261015] [--maxzoom 15]
// Necesita la CLI `pmtiles` (https://github.com/protomaps/go-pmtiles/releases) en el PATH o en PMTILES=<ruta>.
// Imprime el objeto `tiles` para la definición `city` (docs/spec/03): sha256 en `x` y la URL de este espejo.
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'

const args = process.argv.slice(2)
const opt = (name, fallback) => (args.includes(name) ? args[args.indexOf(name) + 1] : fallback)
const [city, bbox] = args.filter((a, i) => !a.startsWith('--') && !args[i - 1]?.startsWith('--'))
if (!/^[a-z]{2}-[a-z0-9-]+$/.test(city ?? '') || !bbox) {
  console.error('usage: node scripts/extract.mjs <city id> <minLat,minLon,maxLat,maxLon> [--build YYYYMMDD] [--maxzoom 15]')
  process.exit(2)
}
const [minLat, minLon, maxLat, maxLon] = bbox.split(',').map(Number)
let build = opt('--build', null)
if (!build) {
  const builds = await fetch('https://build-metadata.protomaps.dev/builds.json').then((r) => r.json())
  build = builds.at(-1).key.replace('.pmtiles', '')
}
const pmtiles = process.env.PMTILES ?? 'pmtiles'
const root = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')
const out = join(root, 'public', city, `${build}.pmtiles`)
mkdirSync(join(root, 'public', city), { recursive: true })
execFileSync(
  pmtiles,
  ['extract', `https://build.protomaps.com/${build}.pmtiles`, out, `--bbox=${minLon},${minLat},${maxLon},${maxLat}`, `--maxzoom=${opt('--maxzoom', '15')}`],
  { stdio: 'inherit' },
)

// Every file served, with size and hash: the Worker needs the sizes to answer ranges.
const files = {}
const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name)
    if (statSync(path).isDirectory()) walk(path)
    else if (name.endsWith('.pmtiles')) {
      const data = readFileSync(path)
      files[`/${relative(join(root, 'public'), path).replaceAll('\\', '/')}`] = {
        size: data.length,
        sha256: createHash('sha256').update(data).digest('hex'),
      }
    }
  }
}
walk(join(root, 'public'))
const lines = Object.entries(files)
  .sort()
  .map(([p, f]) => `  '${p}': { size: ${f.size}, sha256: '${f.sha256}' },`)
writeFileSync(
  join(root, 'src', 'files.ts'),
  `// Generated by scripts/extract.mjs: size and sha256 of every file in public/.\nexport const FILES: Record<string, { size: number; sha256: string }> = {\n${lines.join('\n')}\n}\n`,
)
writeFileSync(
  join(root, 'public', 'index.html'),
  `<!doctype html><meta charset="utf-8"><title>SmartCity tiles</title>\n<p>Mapas base PMTiles de SmartCity: extractos de OpenStreetMap (© colaboradores de OpenStreetMap, ODbL) del build de Protomaps.</p>\n<ul>\n${Object.entries(files)
    .map(([p, f]) => `<li><a href=".${p}">${p.slice(1)}</a> · ${f.size} bytes · sha256 ${f.sha256}</li>`)
    .join('\n')}\n</ul>\n`,
)

const file = files[`/${city}/${build}.pmtiles`]
console.log(`\n${out}: ${file.size} bytes`)
console.log('tiles para la definición city (añade cid y magnet al publicarlo por IPFS y torrent, DIST-1):')
console.log(JSON.stringify({ x: file.sha256, urls: [`https://smartcity-tiles.<cuenta>.workers.dev/${city}/${build}.pmtiles`] }, null, 2))
